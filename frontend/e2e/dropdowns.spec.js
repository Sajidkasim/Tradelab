import { test, expect } from "@playwright/test";

test("Classic menus share retro styling, keyboard selection and viewport-safe placement", async ({ page }, testInfo) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Classic", exact: true }).click();
  await expect(page.locator(".content select")).toHaveCount(0);
  const explorer = page.locator(".explorer");
  for (const label of ["Strategy", "Level timeframe", "Entry timeframe", "Target RR", "Day"]) {
    const control = explorer.getByRole("combobox", { name: label, exact: true });
    await control.click();
    const menu = page.locator(".styled-select-panel");
    await expect(menu).toBeVisible();
    const triggerBox = await control.boundingBox();
    await expect.poll(async () => Math.abs((await menu.boundingBox()).width - Math.max(180, triggerBox.width))).toBeLessThan(2);
    expect(await menu.evaluate((el) => getComputedStyle(el).borderRadius)).toBe("0px");
    const box = await menu.boundingBox();
    expect(box.y).toBeGreaterThanOrEqual(0);
    expect(box.y + box.height).toBeLessThanOrEqual(1000);
    await page.screenshot({ path: testInfo.outputPath(`${label.replaceAll(" ", "-")}.png`) });
    await page.getByRole("listbox", { name: label, exact: true }).press("Escape");
    await expect(control).toBeFocused();
  }
  const timeframe = explorer.getByRole("combobox", { name: "Level timeframe", exact: true });
  await timeframe.press("ArrowDown");
  const list = page.getByRole("listbox", { name: "Level timeframe", exact: true });
  await list.press("1");
  await list.press("h");
  await list.press("Enter");
  await expect(timeframe).toHaveText("1H");
  await timeframe.click();
  await list.press("End");
  await list.press("Home");
  await list.press("Enter");
  await expect(timeframe).toHaveText("Any");
  const level = explorer.getByRole("button", { name: /Key level \/ PDA/ });
  await level.click();
  await page.getByRole("combobox", { name: "Search key level / pda", exact: true }).fill("FVG");
  await page.getByRole("option", { name: "FVG", exact: true }).click();
  await expect(level).toContainText("FVG");
  await page.getByRole("button", { name: "Add trade", exact: true }).click();
  const dialog = page.getByRole("dialog");
  const source = dialog.getByRole("combobox", { name: "Save to", exact: true });
  await source.click();
  await page.getByRole("option", { name: "Live trading", exact: true }).click();
  await expect(source).toHaveText("Live trading");
  await source.click();
  await page.getByRole("listbox", { name: "Save to", exact: true }).press("Escape");
  await expect(dialog).toBeVisible();
  await expect(source).toBeFocused();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await explorer.getByRole("combobox", { name: "Day", exact: true }).click();
  const mobile = await page.locator(".styled-select-panel").boundingBox();
  expect(mobile.x).toBeGreaterThanOrEqual(0);
  expect(mobile.x + mobile.width).toBeLessThanOrEqual(390);
  expect(mobile.y + mobile.height).toBeLessThanOrEqual(844);
  await page.getByRole("option", { name: "Monday", exact: true }).click();
  await expect(explorer.getByRole("combobox", { name: "Day", exact: true })).toHaveText("Monday");
});
