"""Export the existing chart palette as browser design tokens; no new financial colours."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from core.charts import PALETTE

lines = ["/* Generated by tools/web_theme.py from core.charts.PALETTE. */"]
for mode, p in PALETTE.items():
    lines.append(":root {" if mode == "light" else ':root[data-theme="dark"] {')
    for name, value in {"page": p["page"], "surface": p["surface"], "ink": p["ink"], "ink2": p["ink2"], "muted": p["muted"], "border": p["grid"], "accent": p["series"][0], "positive": p["div_pos"], "negative": p["critical"], "warning": p["warning"]}.items():
        lines.append(f"  --tl-{name}: {value};")
    lines.extend([f"  color-scheme: {mode};", "}"])
Path(__file__).resolve().parents[1].joinpath("frontend/src/theme.css").write_text("\n".join(lines) + "\n")
